import { z } from "zod";

const positiveId = z.number().int().positive();
const reportType = z.enum(["client_report", "vendor_report", "internel_report"]);
const scope = z.enum(["internal", "external"]);
const status = z.enum(["initialized", "in_progress", "auto_upload", "paused", "archived"]);
const reportCategory = z.enum([
  "client_report", "vendor_report", "internel_report", "client_cost_injection_report", "p360_report", "schedule_report",
]);
const selectionIds = z.array(z.number().int().nonnegative())
  .refine((ids) => !ids.includes(0) || !ids.some((id) => id > 0), "Cannot combine 0 (all) with specific IDs");
const optionalText = z.string().nullable().optional();
const reportName = z.string().regex(/\S/, "report_name must be nonblank");

export const clientReportRequestsQuerySchema = z.object({
  id: positiveId.optional().describe("Report Request ID"),
  creator_user_id: positiveId.optional().describe("Original creator user ID, including delegated creation"),
  client_id: positiveId.optional().describe("Matches client_ids selections, including [0] (all clients)"),
  vendor_id: positiveId.optional().describe("Matches vendor_ids selections, including [0] (all vendors)"),
  report_name: z.string().optional().describe("Case-insensitive literal substring"),
  report_code: z.string().optional().describe("Exact report code"),
  status: status.optional(),
  report_type: reportType.optional(),
  scope: scope.optional(),
  report_categories: z.array(reportCategory).optional().describe("Matches any supplied category; [] applies no category filter"),
  start_date: z.string().date().optional().describe("Inclusive creation date lower bound in the application time zone"),
  end_date: z.string().date().optional().describe("Inclusive creation date upper bound in the application time zone"),
  automation_start_date: z.string().date().optional().describe("Inclusive lower bound on automation_start_date"),
  automation_end_date: z.string().date().optional().describe("Inclusive upper bound on automation_start_date"),
});

export const clientReportRequestSchema = z.object({
  report_name: reportName.describe("Required nonblank report name"),
  report_type: reportType.nullable().optional().describe("Legacy type; internel_report is the stored spelling. null clears it; use report_categories for new categorization"),
  scope: scope.nullable().optional().describe("null clears the scope"),
  status: status.optional().describe("Defaults to initialized on creation; omitted status is preserved on update"),
  report_categories: z.array(reportCategory).optional().describe("Category values from options; [] clears selections"),
  delivery_methods: z.array(z.enum(["API", "S3", "Email", "Google Sheet", "Google Drive", "SFTP", "Slack"]))
    .optional().describe("Delivery method values from options; [] clears selections"),
  client_ids: selectionIds.optional().describe("Client IDs; [0] selects all, [] clears selections; cannot mix 0 with specific IDs"),
  vendor_ids: selectionIds.optional().describe("Vendor IDs; [0] selects all, [] clears selections; cannot mix 0 with specific IDs"),
  client_id: positiveId.nullable().optional().describe("Legacy singular client reference; prefer client_ids; null clears it"),
  vendor_id: positiveId.nullable().optional().describe("Legacy singular vendor reference; prefer vendor_ids; null clears it"),
  report_config_id: positiveId.nullable().optional().describe("Report Job ID from live options (active and paused jobs); null clears it"),
  schedule_export_id: positiveId.nullable().optional().describe("Verified Schedule Export ID for schedule_report; null clears it"),
  automation_start_date: z.string().date().nullable().optional().describe("YYYY-MM-DD; null clears the date"),
  pm: optionalText.describe("PM email string; historical/custom values accepted"),
  pa: optionalText.describe("PA email string; historical/custom values accepted"),
  dev: optionalText.describe("Developer email string; historical/custom values accepted"),
  request_user: optionalText.describe("Request user email string; historical/custom values accepted"),
  business_proposal: optionalText,
  github_ticket: optionalText,
  hubspot_ticket: optionalText,
  data_source: optionalText,
  note: optionalText,
  destination: optionalText,
  report_code: optionalText.describe("Generated by the API when absent on creation"),
  on_behalf_of_user_id: positiveId.optional().describe("Optional verified requester's FeedMob user ID. Resolve from trusted session identity and a verified user mapping. Sent at the top level; requires action-specific execution and delegation permissions. Attributes creator on creation and audits to the requester; preserve on retries"),
});

export const updateClientReportRequestSchema = clientReportRequestSchema.partial().extend({
  id: positiveId.describe("Existing Report Request ID"),
  report_name: reportName.optional().describe("Optional new nonblank report name; omitted name is preserved"),
});

export type ClientReportRequestsQuery = z.infer<typeof clientReportRequestsQuerySchema>;
export type CreateClientReportRequestParams = z.infer<typeof clientReportRequestSchema>;
export type UpdateClientReportRequestParams = z.infer<typeof updateClientReportRequestSchema>;
